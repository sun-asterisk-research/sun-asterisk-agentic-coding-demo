    def test_transaction_indexes_exist(self):
        """
        Test that database indexes are created for Transaction model.

        According to T011, Transaction should have indexes on:
        - [user, date]
        - [user, type]
        - [category]
        """
        from transactions.models import Transaction
        table_name = Transaction._meta.db_table

        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT indexname
                FROM pg_indexes
                WHERE tablename = %s
            """, [table_name])
            indexes = [row[0] for row in cursor.fetchall()]

        # Check that we have indexes (exact names are auto-generated by Django)
        # Just verify there are multiple indexes beyond the primary key
        self.assertGreater(
            len(indexes),
            1,
            f"Expected multiple indexes on {table_name}, found {len(indexes)}. "
            "Verify migrations include index definitions."
        )

    def test_userprofile_has_correct_fields(self):
        """Test UserProfile table has all expected fields."""
        from accounts.models import UserProfile

        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT column_name
                FROM information_schema.columns
                WHERE table_name = %s
            """, [UserProfile._meta.db_table])
            columns = [row[0] for row in cursor.fetchall()]

        expected_fields = [
            'id', 'user_id', 'display_name', 'avatar',
            'monthly_budget', 'created_at', 'updated_at'
        ]

        for field in expected_fields:
            self.assertIn(
                field,
                columns,
                f"Field {field} not found in {UserProfile._meta.db_table}. "
                "Check migrations."
            )

