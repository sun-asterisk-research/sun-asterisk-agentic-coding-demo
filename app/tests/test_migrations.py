"""
Tests for database migrations.

This module contains tests to verify that all migrations are created
and applied correctly for all apps in the project.
"""

from django.test import TestCase
from django.db import connection
from django.apps import apps


class MigrationTest(TestCase):
    """Test suite for verifying database migrations."""

    def test_all_models_have_tables_in_database(self):
        """
        Test that all Django models have corresponding tables in database.

        This verifies that migrations have been created and applied for all
        models defined in the project apps.
        """
        # Get all installed app models
        all_models = apps.get_models()

        # Get all table names in database
        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = 'public'
            """)
            db_tables = [row[0] for row in cursor.fetchall()]

        # Check each model has a corresponding table
        for model in all_models:
            # Skip Django's built-in models like ContentType, Session, etc.
            app_label = model._meta.app_label
            if app_label in ['accounts', 'transactions', 'reports']:
                table_name = model._meta.db_table
                self.assertIn(
                    table_name,
                    db_tables,
                    f"Table {table_name} for model {model.__name__} "
                    f"not found in database. Migration may not be applied."
                )

    def test_accounts_userprofile_model_exists(self):
        """Test that UserProfile model from accounts app has database table."""
        from accounts.models import UserProfile

        with connection.cursor() as cursor:
            cursor.execute("""
                SELECT table_name
                FROM information_schema.tables
                WHERE table_name = %s
            """, [UserProfile._meta.db_table])
            result = cursor.fetchone()

        self.assertIsNotNone(
            result,
            "accounts_userprofile table not found. "
            "Run makemigrations and migrate."
        )

